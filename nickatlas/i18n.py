def set_language(value):
    global LANGUAGE
    LANGUAGE = value if value in ("en", "ru") else "en"


def tr(text):
    text = str(text)
    mapping = RU_EN if LANGUAGE == "en" else EN_RU
    if text in mapping:
        return mapping[text]
    urls = re.findall(r"https?://[^\s]+", text)
    for i, url in enumerate(urls):
        text = text.replace(url, f"__NIX_URL_{i}__", 1)
    for source in sorted(mapping, key=len, reverse=True):
        if source and source in text:
            text = text.replace(source, mapping[source])
    for i, url in enumerate(urls):
        text = text.replace(f"__NIX_URL_{i}__", url)
    return text


